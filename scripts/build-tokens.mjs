// Generates CSS from tokens/tokens.json. Run with: npm run tokens
//   src/styles/variables.css  CSS custom properties (:root = Light, .dark = Dark)
//   src/styles/theme.css      Tailwind theme mapping (bg-surface-page, rounded-md, text-heading-h1 ...)
// Variable names follow the WEB code syntax set in Figma, e.g. --palette-primary-600, --color-surface-page.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'tokens/tokens.json'), 'utf8'));
const header = '/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n';

// Walk a token group and yield [path segments, token] for every leaf token.
function* leaves(group, trail = []) {
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    if (node && typeof node === 'object' && '$value' in node) yield [[...trail, key], node];
    else if (node && typeof node === 'object') yield* leaves(node, [...trail, key]);
  }
}

const cssName = segments => `--${segments.join('-')}`;
// "{palette.neutral.50}" -> "var(--palette-neutral-50)"
const resolve = value => String(value).replace(/\{([^}]+)\}/g, (_, ref) => `var(${cssName(ref.split('.'))})`);
const shadow = layers =>
  layers.map(l => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${resolve(l.color)}`).join(', ');

// ---------- variables.css ----------
const light = [];
const dark = [];
for (const group of ['palette', 'color', 'spacing', 'radius', 'font-family', 'font-size', 'font-weight', 'shadow']) {
  light.push(`\n  /* ${group} */`);
  for (const [segments, token] of leaves(tokens[group], [group])) {
    const name = cssName(segments);
    if (token.$type === 'shadow') light.push(`  ${name}: ${shadow(token.$value)};`);
    else if (token.$type === 'fontFamily') light.push(`  ${name}: '${token.$value}', ui-sans-serif, system-ui, sans-serif;`);
    else light.push(`  ${name}: ${resolve(token.$value)};`);
    const darkValue = token.$extensions?.modes?.dark;
    if (darkValue) dark.push(`  ${name}: ${resolve(darkValue)};`);
  }
}
const variablesCss = `${header}
:root {${light.join('\n')}
}

.dark {
  color-scheme: dark;
${dark.join('\n')}
}
`;

// ---------- theme.css (Tailwind v4) ----------
// "inline reference": utilities point straight at the variables above, and Tailwind does not
// emit its own copies (they would clash, because Figma names already use Tailwind's prefixes).
const theme = ['@theme inline reference {'];
const map = (comment, reset, entries) => {
  theme.push(`\n  /* ${comment} */`, `  ${reset}: initial;`);
  for (const [key, value] of entries) theme.push(`  ${key}: ${value};`);
};
map('Semantic colours only. Primitives are never used directly in components.', '--color-*',
  [...leaves(tokens.color, ['color'])].map(([s]) => [cssName(s), `var(${cssName(s)})`]));
map('Spacing scale. Only the Figma steps exist (p-4 = 16px, gap-2 = 8px ...).', '--spacing-*',
  [...leaves(tokens.spacing, ['spacing'])].map(([s]) => [cssName(s), `var(${cssName(s)})`]));
map('Radius', '--radius-*',
  [...leaves(tokens.radius, ['radius'])].map(([s]) => [cssName(s), `var(${cssName(s)})`]));
map('Font family', '--font-*', [['--font-sans', 'var(--font-family-sans)']]);
map('Font weights', '--font-weight-*',
  [...leaves(tokens['font-weight'], ['font-weight'])].map(([s]) => [cssName(s), `var(${cssName(s)})`]));
map('Text styles from Figma: text-heading-h1, text-body-base, text-label-small ...', '--text-*',
  [...leaves(tokens.typography)].flatMap(([s, { $value: v }]) => {
    const name = `--text-${s.join('-')}`;
    return [
      [name, resolve(v.fontSize)],
      [`${name}--line-height`, v.lineHeight],
      [`${name}--font-weight`, resolve(v.fontWeight)],
      [`${name}--letter-spacing`, v.letterSpacing],
    ];
  }));
map('Shadows and focus ring', '--shadow-*',
  [...leaves(tokens.shadow, ['shadow'])].map(([s]) => [cssName(s), `var(${cssName(s)})`]));
theme.push('}');

const outDir = path.join(root, 'src/styles');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'variables.css'), variablesCss);
fs.writeFileSync(path.join(outDir, 'theme.css'), `${header}\n${theme.join('\n')}\n`);
console.log('Tokens written to src/styles/variables.css and src/styles/theme.css');
